def get_plants_by_category(cat_key: str) -> list[tuple[int, dict]]:
    """Return list of (global_index, plant) for the given category key."""
    target_ar = CATEGORY_KEYS.get(cat_key, "")
    return [(i, p) for i, p in enumerate(PLANTS) if p["category_ar"] == target_ar]


def get_plant_by_index(idx: int) -> dict | None:
    if 0 <= idx < len(PLANTS):
        return PLANTS[idx]
    return None


def _normalize(text: str) -> str:
    return text.strip().lower()


def search_plant(query: str) -> dict | None:
    """Return best matching plant or None."""
    q = _normalize(query)
    # 1. Exact Arabic name match
    for p in PLANTS:
        if _normalize(p["ar_name"]) == q:
            return p
    # 2. Exact English name match
    for p in PLANTS:
        if _normalize(p["en_name"]) == q:
            return p
    # 3. Alias match
    for p in PLANTS:
        for alias in p["aliases"]:
            if _normalize(alias) == q:
                return p
    # 4. Partial Arabic name or alias
    for p in PLANTS:
        if q in _normalize(p["ar_name"]) or _normalize(p["ar_name"]) in q:
            return p
        for alias in p["aliases"]:
            if q in _normalize(alias) or _normalize(alias) in q:
                return p
    # 5. Partial English name
    for p in PLANTS:
        if q in _normalize(p["en_name"]) or _normalize(p["en_name"]) in q:
            return p
    return None


